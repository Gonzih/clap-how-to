#!/usr/bin/env python3
"""Reproduce the bundled model. Explicit development tool; never a build script.

Python standard library only. Download pinned, hash-checked upstream files,
quantize every F32 matrix in flattened groups of 32 to symmetric signed 4-bit
values, keep F16 scales and original 1-D F32 tensors. Inference dequantizes once.
"""
import argparse, array, hashlib, json, math, pathlib, struct, sys, urllib.request

MODEL = 'sentence-transformers/paraphrase-MiniLM-L3-v2'
REVISION = '4ca70771034acceecb2e72475f72050fcdde4ddc'
HASHES = {
    'model.safetensors': 'cf1e4e2d420c664973037c3c73125d7a8fc69952495093ef8f50596f8943a433',
    'config.json': 'fc00f0ca1c3380f17937a4050908dd2cf743c36bebe437cf448b8aa4e7ddfe4d',
    'tokenizer.json': 'a9576e4dadfe7f78f071a1c00ba6902cc83ec6ed7e9b590ee974950bd4d54393',
}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input-dir', type=pathlib.Path)
    args = parser.parse_args()
    root = pathlib.Path(__file__).resolve().parents[1]
    inputs = args.input_dir or root / '.kb/runs/research/neural'
    output = root / 'pocket-encoder/assets'
    inputs.mkdir(parents=True, exist_ok=True)
    output.mkdir(parents=True, exist_ok=True)
    for name, expected in HASHES.items():
        path = inputs / name
        if not path.exists():
            urllib.request.urlretrieve(f'https://huggingface.co/{MODEL}/resolve/{REVISION}/{name}', path)
        assert hashlib.sha256(path.read_bytes()).hexdigest() == expected, name
    raw = (inputs / 'model.safetensors').read_bytes()
    size = struct.unpack('<Q', raw[:8])[0]
    header = json.loads(raw[8:8+size])
    original = memoryview(raw)[8+size:]
    tensors, payload, shapes = {}, bytearray(), {}
    def add(name, data, dtype, shape):
        start = len(payload)
        payload.extend(data)
        tensors[name] = dict(dtype=dtype, shape=shape, data_offsets=[start, len(payload)])
    for name, info in sorted(header.items()):
        if name == '__metadata__' or info['dtype'] != 'F32':
            continue  # position_ids are generated by Candle, not learned weights
        data = original[slice(*info['data_offsets'])]
        shape = info['shape']
        shapes[name] = shape
        if len(shape) < 2:
            add(name, data, 'F32', shape)
            continue
        values = array.array('f'); values.frombytes(data)
        if sys.byteorder != 'little': values.byteswap()
        packed, scales = bytearray(), bytearray()
        for offset in range(0, len(values), 32):
            group = values[offset:offset+32]
            scale = max(map(abs, group)) / 7 or 1.0
            scales.extend(struct.pack('<e', scale))
            quant = [max(-7, min(7, round(v / scale))) + 8 for v in group]
            for i in range(0, len(quant), 2):
                packed.append(quant[i] | ((quant[i+1] if i+1 < len(quant) else 8) << 4))
        add(name + '.q4', packed, 'U8', [len(packed)])
        add(name + '.scales', scales, 'F16', [len(scales)//2])
    encoded = json.dumps(tensors, separators=(',', ':'), sort_keys=True).encode()
    encoded += b' ' * ((8-len(encoded) % 8) % 8)
    bundle = struct.pack('<Q', len(encoded)) + encoded + payload
    (output / 'model.safetensors').write_bytes(bundle)
    (output / 'shapes.json').write_text(json.dumps(shapes, sort_keys=True, indent=2)+'\n')
    for name in ['config.json', 'tokenizer.json']:
        (output/name).write_bytes((inputs/name).read_bytes())
    provenance = dict(upstream_model=MODEL, upstream_revision=REVISION,
        upstream_sha256=HASHES, bundled_sha256=hashlib.sha256(bundle).hexdigest(),
        quantization='q4-symmetric-g32-f16-v1: round-to-even, [-7,7], nibble=q+8, low nibble first, float16 group scale=max(abs)/7; zero group scale=1',
        dimensions=384, max_tokens=128, pooling='attention-masked mean; L2 normalized',
        tokenizer_sha256=HASHES['tokenizer.json'], license='Apache-2.0', network_at_build_or_inference=False)
    (output/'provenance.json').write_text(json.dumps(provenance, indent=2)+'\n')
    print(json.dumps(dict(bytes=len(bundle), sha256=provenance['bundled_sha256'])))

if __name__ == '__main__':
    main()
